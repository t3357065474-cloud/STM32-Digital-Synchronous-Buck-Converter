/* ──── 软件I2C ──── */
static void OLED_I2C_Start(void)
{
  HAL_GPIO_WritePin(OLED_SDA_GPIO, OLED_SDA, GPIO_PIN_SET);
  HAL_GPIO_WritePin(OLED_SCL_GPIO, OLED_SCL, GPIO_PIN_SET);
  HAL_GPIO_WritePin(OLED_SDA_GPIO, OLED_SDA, GPIO_PIN_RESET);
  HAL_GPIO_WritePin(OLED_SCL_GPIO, OLED_SCL, GPIO_PIN_RESET);
}

static void OLED_I2C_Stop(void)
{
  HAL_GPIO_WritePin(OLED_SDA_GPIO, OLED_SDA, GPIO_PIN_RESET);
  HAL_GPIO_WritePin(OLED_SCL_GPIO, OLED_SCL, GPIO_PIN_SET);
  HAL_GPIO_WritePin(OLED_SDA_GPIO, OLED_SDA, GPIO_PIN_SET);
}

static void OLED_I2C_WriteByte(uint8_t byte)
{
  uint8_t i;
  for (i = 0; i < 8; i++)
  {
    HAL_GPIO_WritePin(OLED_SDA_GPIO, OLED_SDA,
                      (byte & 0x80) ? GPIO_PIN_SET : GPIO_PIN_RESET);
    byte <<= 1;
    /* 高电平脉宽加长，方便示波器观察，也提高软件I2C鲁棒性 */
    HAL_GPIO_WritePin(OLED_SCL_GPIO, OLED_SCL, GPIO_PIN_SET);
    HAL_GPIO_WritePin(OLED_SCL_GPIO, OLED_SCL, GPIO_PIN_RESET);
  }
  /* 第9个时钟：忽略从机应答 */
  HAL_GPIO_WritePin(OLED_SCL_GPIO, OLED_SCL, GPIO_PIN_SET);
  HAL_GPIO_WritePin(OLED_SCL_GPIO, OLED_SCL, GPIO_PIN_RESET);
}

/* 发送一帧：mode=0x00命令 / 0x40数据 */
static void OLED_Send(uint8_t mode, const uint8_t *data, uint16_t len)
{
  uint16_t i;
  OLED_I2C_Start();
  OLED_I2C_WriteByte(OLED_ADDR);
  OLED_I2C_WriteByte(mode);
  for (i = 0; i < len; i++) OLED_I2C_WriteByte(data[i]);
  OLED_I2C_Stop();
}

static void OLED_WriteCmd(uint8_t cmd)
{
  OLED_Send(0x00, &cmd, 1);
}

/* ──── 初始化（标准 SSD1306 初始化序列，128x64）──── */
void OLED_Init(void)
{
  uint8_t cmds[] = {
    0xAE,             /* 关闭显示 */
    0x20, 0x00,       /* 水平寻址模式 */
    0x21, 0x00, 0x7F, /* 列地址 0~127 */
    0x22, 0x00, 0x07, /* 页地址 0~7 */
    0xA8, 0x3F,       /* 多路复用 64行 */
    0xD3, 0x00,       /* 显示偏移 0 */
    0x40,             /* 显示起始行 0 */
    0x8D, 0x14,       /* 电荷泵开启（I2C屏必须有） */
    0xA1,             /* 段重映射（列0在右） */
    0xC8,             /* COM扫描方向（上下翻转） */
    0xDA, 0x12,       /* COM引脚配置 */
    0x81, 0x7F,       /* 对比度 */
    0xD9, 0xF1,       /* 预充电周期 */
    0xDB, 0x30,       /* VCOMH */
    0xA4,             /* 正常显示 */
    0xA6,             /* 不反色 */
    0xAF              /* 开启显示 */
  };
  uint8_t i;
  for (i = 0; i < sizeof(cmds); i++) OLED_WriteCmd(cmds[i]);

  /* 首次上屏把全屏清掉（Prev置0xFF强制第一次全发） */
  memset(OLED_Buf, 0, sizeof(OLED_Buf));
  memset(OLED_Prev, 0xFF, sizeof(OLED_Prev));
  OLED_Update();
}

/* ──── 显存操作 ──── */
void OLED_Clear(void)
{
  memset(OLED_Buf, 0, sizeof(OLED_Buf));
}

void OLED_Update(void)
{
  uint8_t page;
  for (page = 0; page < OLED_PAGES; page++)
  {
    uint8_t *cur  = &OLED_Buf[page * OLED_WIDTH];
    uint8_t *prev = &OLED_Prev[page * OLED_WIDTH];
    if (memcmp(cur, prev, OLED_WIDTH) == 0) continue;   /* 本页没变化，跳过 */

    uint8_t cmds[3] = {0xB0 + page, 0x10, 0x00};        /* 设页 + 列=0 */
    OLED_Send(0x00, cmds, 3);
    OLED_Send(0x40, cur, OLED_WIDTH);                   /* 整页128字节 */
    memcpy(prev, cur, OLED_WIDTH);
  }
}

/* 画一个字符到显存（x:列0~15 y:行0~7） */
static void OLED_DrawChar(uint8_t x, uint8_t y, char ch)
{
  uint8_t i;
  if (x > 15 || y > 7) return;
  if (ch < 0x20 || ch > 0x7E) ch = ' ';
  uint8_t *p = &OLED_Buf[y * OLED_WIDTH + x * 8];
  for (i = 0; i < 8; i++) p[i] = 0;                     /* 清8列再画6列 */
  for (i = 0; i < 6; i++) p[i] = OLED_Font[ch - 0x20][i];
}

/* ──── 对外显示接口 ──── */
void OLED_ShowString(uint8_t x, uint8_t y, const char *str)
{
  while (*str != '\0')
  {
    if (x > 15) break;
    OLED_DrawChar(x, y, *str);
    x++;
    str++;
  }
}

void OLED_ShowNumber(uint8_t x, uint8_t y, int32_t num, uint8_t len)
{
  char buf[12];
  uint8_t i, negative = 0;
  int32_t n = num;
  if (len > 10) len = 10;
  if (n < 0) { negative = 1; n = -n; }   /* n取正；对INT32_MIN会溢出，但显示10位以内不涉及 */
  for (i = len; i > 0; i--)
  {
    buf[i - 1] = (char)('0' + (n % 10));
    n /= 10;
  }
  if (negative && len > 0) buf[0] = '-';
  buf[len] = '\0';
  OLED_ShowString(x, y, buf);
}

void OLED_ShowDecimal(uint8_t x, uint8_t y, float num, uint8_t ilen, uint8_t flen)
{
  if (num < 0)
  {
    OLED_ShowString(x, y, "-");
    x++;
    num = -num;
  }

  int32_t ipart = (int32_t)num;
  int32_t scale = 1;
  uint8_t i;
  if (flen > 9) flen = 9;                      /* 防止scale溢出 */
  for (i = 0; i < flen; i++) scale *= 10;
  int32_t fpart = (int32_t)((num - ipart) * scale + 0.5f);   /* 四舍五入 */
  if (fpart >= scale) { fpart = 0; ipart++; }                /* 小数进位到整数 */

  OLED_ShowNumber(x, y, ipart, ilen);
  x += ilen;
  if (x > 15) return;
  OLED_ShowString(x, y, ".");
  OLED_ShowNumber(x + 1, y, fpart, flen);
}
