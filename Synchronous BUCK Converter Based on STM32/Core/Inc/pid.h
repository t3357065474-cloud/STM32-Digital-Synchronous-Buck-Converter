/**
  * @file    pid.h
  * @brief   PID 控制模块（增量式PID，纯C算法，不依赖任何硬件）
  *
  * ────────────────────────────────────────────────────────────
  * 什么是增量式PID
  * ────────────────────────────────────────────────────────────
  * 位置式PID：输出 = 直接算出的控制量（带积分累计，易积分饱和）
  * 增量式PID：输出 = 上次输出 + 本次变化量 Δu
  *   Δu = kp*(e_k - e_k-1) + ki*e_k + kd*(e_k - 2*e_k-1 + e_k-2)
  * 电源设计里常用增量式：每次只加一点，输出平滑，天然防饱和
  *
  * ────────────────────────────────────────────────────────────
  * 使用方法（以Buck电压环为例）
  * ────────────────────────────────────────────────────────────
  * 1) 在 main.c 中 include：
  *       #include "pid.h"
  *
  * 2) 定义一个PID实例并初始化（main开头或全局）：
  *       PID_Handle v_pid;
  *       PID_Init(&v_pid, 0.01f, 1.0f, 0.0f, 5, 3419, 0);
  *       //           kp    ki    kd  单次增量限幅 输出上限 输出下限
  *
  * 3) 在固定周期的控制里调用一次（如定时器中断，每1ms一次）：
  *       pwm_ccr = (uint16_t)PID_Update(&v_pid, v_ref, vout);
  *       //                 目标值    实际值 → 返回控制量(占空比)
  *
  * ────────────────────────────────────────────────────────────
  * PID 调参步骤（重要！按顺序来）
  * ────────────────────────────────────────────────────────────
  * 第0步 准备：
  *       - 确定调用周期固定（本项目1ms，由TIM1更新中断保证）
  *       - 观察工具：示波器/万用表看输出电压曲线，
  *         或VOFA+看vout曲线（本项目已接好）
  *
  * 第1步 只留比例：把 ki 和 kd 设为 0，只调 kp
  *       - 从很小开始（如0.001），逐步加大，观察启动过程
  *       - 现象判断：
  *           · 响应慢、爬得慢 → kp 太小，加大
  *           · 输出电压持续振荡（锯齿/波浪）→ kp 太大，减小
  *           · 波形刚好不振荡、又能快速跟上 → kp 合适
  *       - 此时输出电压和目标会有固定偏差（稳态误差），正常，下一步消除
  *
  * 第2步 加入积分：固定 kp，从很小加 ki（如0.1），逐步加大
  *       - 作用：消除第1步留下的稳态误差
  *       - 现象判断：
  *           · 误差始终消不掉 → ki 太小，加大
  *           · 输出电压振荡 → ki 太大，减小
  *           · 电压能稳定到目标值、无振荡 → 调好了
  *
  * 第3步（可选）加微分 kd：只有过冲严重时才需要
  *       - 从很小加（如0.001），观察过冲是否减小
  *       - 加了反而噪声大/更抖 → 说明不需要D，设回0
  *
  * 第4步 单次增量限幅 delta_max（防突变）：
  *       - 电源一般 5~50。越大响应越快但易震荡，越小越稳越慢
  *       - 从 5 起步，若响应太慢适当加大
  *
  * 第5步 负载突变测试：输出稳定后，突然加/减负载
  *       - 电压跌落小、恢复快 → 调得好
  *       - 电压跌太多或长时间不恢复 → 加大 kp/ki 再微调
  *       - 恢复过程中振荡 → 减小 kp/ki
  *
  * ────────────────────────────────────────────────────────────
  * 调参口诀
  * ────────────────────────────────────────────────────────────
  *       追不上（响应慢）→ 加大 kp
  *       振荡（不稳）    → 减小 kp 或 ki
  *       有偏差（消不掉）→ 加大 ki
  *       过冲（冲过头）  → 加 kd 或 减小 ki
  * 一次只改一个参数，改完观察稳定了再改下一个。
  *
  * 5) 重要技巧：
  *       - PID_Update 是纯计算，【调用周期必须固定】（如每1ms），
  *         周期变化会让调好的参数失效
  *       - 反馈量单位要和目标量一致（都用电压V，或都用ADC码值）
  *       - 输出从 output_min 起步，配合软启动正好从0爬升
  *       - 本模块纯C、零依赖，任何平台都能直接拷贝用
  *
  * 6) 内置两个工程特性（不用你管，自动生效）：
  *       - 抗积分饱和：输出卡在限幅时自动削弱积分，防止误差反向后过冲
  *       - 微分滤波：D项过一阶低通，抑制ADC高频抖动进入控制量
  * ────────────────────────────────────────────────────────────
  */
#ifndef __PID_H
#define __PID_H

typedef struct
{
  float kp;          /* 比例系数（增量式里管Δe） */
  float ki;          /* 积分系数（管e，消除稳态误差） */
  float kd;          /* 微分系数（管二阶差分，一般可设0） */
  float delta_max;   /* 单次输出增量上限，防突变震荡 */
  float output_max;  /* 输出上限 */
  float output_min;  /* 输出下限 */
  float ek_1;        /* 内部：上次误差 */
  float ek_2;        /* 内部：上上次误差 */
  float output;      /* 内部：当前输出 */
  float d_filt;      /* 内部：微分滤波上次值（抑制高频噪声） */
} PID_Handle;

/* 初始化PID：kp/ki/kd三个系数，delta_max单次增量上限，
 * output_max/output_min输出限幅（如0~3419） */
void PID_Init(PID_Handle *pid, float kp, float ki, float kd,
              float delta_max, float output_max, float output_min);

/* 清零PID内部状态（输出/历史误差/微分滤波），
 * 保留参数配置不变。用于停机、过流锁存复位后，软启动真正从0爬升 */
void PID_Reset(PID_Handle *pid);

/* 执行一次PID运算：传入目标值setpoint和实际值feedback，
 * 返回控制量（输出限幅内） */
float PID_Update(PID_Handle *pid, float setpoint, float feedback);

#endif /* __PID_H */
